import { requireJsonBody } from '../../middleware/json-body';
import { studentWindows } from '../students/registration-options.service';
import { Router,type RequestHandler } from 'express';
import { authenticate } from '../../middleware/authenticate';
import { authorizeRoles } from '../../middleware/authorize';
import { positiveId } from '../students/student.validation';
import { listWindows,saveWindow } from './window.service';
import { listRegistrations,review } from './registration.service';
import { submitStudentDossier } from '../qhdn/student-submission.service';
import { handoffHistory,semesterStudents } from './handoff.service';
import { saveRegistrationSettings, effectiveRegistrationStatus } from '../qhdn/registration-settings.service';
const router=Router(),qhdn=[authenticate,authorizeRoles('ADMIN','OJT_COORD')],read=[authenticate,authorizeRoles('ADMIN','ACADEMIC','STUDENT')];
const handle=(work:(req:any)=>Promise<unknown>,status=200):RequestHandler=>async(req,res,next)=>{try{res.status(status).json({success:true,data:await work(req)});}catch(error){next(error);}};
router.get('/ojt-registration-windows',authenticate,authorizeRoles('ADMIN','OJT_COORD','STUDENT'),handle(async req=>{
  if(req.user.roleCode==='STUDENT')return studentWindows('ojt',req.query,req.user);
  const result=await listWindows(req.query);
  return req.user.roleCode==='OJT_COORD'?{...result,items:result.items.map(item=>({...item,effectiveStatus:effectiveRegistrationStatus(item)}))}:result;
}));
router.post('/ojt-registration-windows',authenticate,authorizeRoles('ADMIN'),handle(req=>saveWindow(req.body,req.user.userId),201));
router.patch('/ojt-registration-windows/:id',authenticate,authorizeRoles('ADMIN'),handle(req=>saveWindow(req.body,req.user.userId,positiveId(req.params.id))));
router.put('/qhdn/ojt-semesters/:id/registration-settings',authenticate,authorizeRoles('OJT_COORD'),requireJsonBody,handle(req=>saveRegistrationSettings(positiveId(req.params.id),req.body,req.user)));
router.post('/ojt-registrations',authenticate,authorizeRoles('ADMIN','STUDENT'),requireJsonBody,handle(req=>submitStudentDossier(req.body,req.user),201));
router.get('/ojt-registrations',authenticate,authorizeRoles('ADMIN','STUDENT'),handle(req=>listRegistrations(req.query,req.user)));
router.post('/ojt-registrations/:id/review',...qhdn,handle(req=>review(positiveId(req.params.id),req.body,req.user.userId)));
router.get('/ojt-semesters/:id/eligible-student-handoffs',authenticate,authorizeRoles('ADMIN','OJT_COORD'),handle(req=>handoffHistory(positiveId(req.params.id),req.query)));
router.get('/ojt-semesters/:id/students',...read,handle(req=>semesterStudents(positiveId(req.params.id),req.query,req.user)));
export default router;

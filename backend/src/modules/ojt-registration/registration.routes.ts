import { requireJsonBody } from '../../middleware/json-body';
import { studentWindows } from '../students/registration-options.service';
import { Router,type RequestHandler } from 'express';
import { authenticate } from '../../middleware/authenticate';
import { authorizeRoles } from '../../middleware/authorize';
import { positiveId } from '../students/student.validation';
import { listWindows,saveWindow } from './window.service';
import { submit,listRegistrations } from './registration.service';
const router=Router(),qhdn=[authenticate,authorizeRoles('ADMIN','OJT_COORD')];
const handle=(work:(req:any)=>Promise<unknown>,status=200):RequestHandler=>async(req,res,next)=>{try{res.status(status).json({success:true,data:await work(req)});}catch(error){next(error);}};
router.get('/ojt-registration-windows',authenticate,authorizeRoles('ADMIN','OJT_COORD','STUDENT'),handle(req=>req.user.roleCode==='STUDENT'?studentWindows('ojt',req.query,req.user):listWindows(req.query)));
router.post('/ojt-registration-windows',...qhdn,handle(req=>saveWindow(req.body,req.user.userId),201));
router.patch('/ojt-registration-windows/:id',...qhdn,handle(req=>saveWindow(req.body,req.user.userId,positiveId(req.params.id))));
router.post('/ojt-registrations',authenticate,authorizeRoles('ADMIN','STUDENT'),requireJsonBody,handle(req=>submit(req.body,req.user),201));
router.get('/ojt-registrations',authenticate,authorizeRoles('ADMIN','OJT_COORD','STUDENT'),handle(req=>listRegistrations(req.query,req.user)));
export default router;

import { Router,type RequestHandler } from 'express';
import { authenticate } from '../../middleware/authenticate';
import { authorizeRoles } from '../../middleware/authorize';
import { positiveId } from '../students/student.validation';
import { createAdvisoryRun,advisoryRuns,schedule } from './advisory.service';
const router=Router(),staff=[authenticate,authorizeRoles('ADMIN','ACADEMIC')];
const handle=(work:(req:any)=>Promise<unknown>,status=200):RequestHandler=>async(req,res,next)=>{try{res.status(status).json({success:true,data:await work(req)});}catch(e){next(e);}};
router.post('/academic/academic-summary-notifications',...staff,handle(r=>createAdvisoryRun(r.body,r.user,'SUMMARY'),202));
router.post('/academic/eligibility-notifications',...staff,handle(r=>createAdvisoryRun(r.body,r.user,'ELIGIBILITY'),202));
router.get('/academic-periods/:id/ojt-advisory-schedule',...staff,handle(r=>schedule(positiveId(r.params.id),r.user)));
router.put('/academic-periods/:id/ojt-advisory-schedule',...staff,handle(r=>schedule(positiveId(r.params.id),r.user,r.body)));
router.get('/academic/advisory-runs',...staff,handle(r=>advisoryRuns(r.query,r.user)));
router.get('/academic/advisory-runs/:id',...staff,handle(r=>advisoryRuns(r.query,r.user,positiveId(r.params.id))));
export default router;
